//! The tool that puts a mesh back into objects and groups (issue 108).
//!
//! Separates the mesh into bodies, recognises rebuildable shapes, and replaces the mesh with a
//! group of editable objects. See [`simple3d_geom::reassemble`] for the recognition.
//!
//! Unlike the simplify tool, the result is drawn over the mesh and only enters the document on
//! Reassemble: it is a new subtree, and swapping it in on every change would rebuild the outliner
//! under the pointer. Recognised shapes are drawn as built and the rest as boxes, over the
//! document's [`PreviewViewport`](simple3d_core::scene::PreviewViewport) setting. A non-modal
//! [in-place popup](crate::popup), so the model can be orbited while tuning.

